'use strict';

const fs = require('node:fs');
const path = require('node:path');
const lab = path.resolve(__dirname, '..');
const game = path.resolve(lab, '../../js/09-mainloop.js');
const { src, bpm, firstBeat, duration } = require('../songs.json')
  .find(song => song.id === 'alley-cat').versions[0];
const track = { id: 'alley-cat', src: 'music/' + path.basename(src), bpm, firstBeat, duration };
const loop = require('../alley-cat-loop.json');
const authored = {
  steady: require('../charts/alley-steady.json'),
  fast: require('../charts/alley-fast.json'),
};
const profiles = Object.fromEntries(Object.entries(loop.profiles)
  .map(([key, { src, segments, accents }]) => [key, { src, segments, accents }]));
const runtimeLoop = { bpm: loop.bpm, firstBeat: loop.firstBeat, beats: loop.beats, duration: loop.duration,
  preroll: loop.preroll, profiles };
const begin = '/* BEGIN DANCE SOURCES — generated by tools/dance-lab/tools/embed-game.js */';
const end = '/* END DANCE SOURCES */';
const modules = ['chart', 'judge'].map(name => fs.readFileSync(path.join(lab, name + '.js'), 'utf8').trimEnd());
const block = [begin, ...modules, 'const DN_TRACK=' + JSON.stringify(track) + ';', 'const DN_LOOP=' + JSON.stringify(runtimeLoop) + ';',
  'const DN_AUTHORED=' + JSON.stringify(authored) + ';', end].join('\n');
const original = fs.readFileSync(game, 'utf8');
const start = original.indexOf(begin), stop = original.indexOf(end);
if (start === -1 || stop <= start) throw new Error('Dance source markers are missing');
const result = original.slice(0, start) + block + original.slice(stop + end.length);
if (process.argv.includes('--check')) {
  if (result !== original) throw new Error('Regenerate the game’s dance sources');
} else {
  fs.writeFileSync(game, result);
}
